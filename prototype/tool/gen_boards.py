#!/usr/bin/env python3
"""Generate lib/boards.dart, lib/router.dart and missing screen stubs.

Inputs (README M0 step 3): canvas.json, board-manifest.json and the
`json computed-links` / `json child-routes` blocks of docs/build/navigation.md.
Run from anywhere: python3 prototype/tool/gen_boards.py
"""
import json
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parents[2]
PROTO = ROOT / 'prototype'
CANVAS = json.loads((ROOT / 'docs/design/handoff/canvas/canvas.json').read_text())
MANIFEST = json.loads((ROOT / 'docs/build/board-manifest.json').read_text())['boards']
NAV = (ROOT / 'docs/build/navigation.md').read_text()


def blok(tag):
    m = re.search(r'```json ' + tag + r'\n(.*?)\n```', NAV, re.S)
    return json.loads(m.group(1))


COMPUTED = blok('computed-links')
CHILD = blok('child-routes')


def stem(f):
    return f[:-len('.dc.html')]


def snake(s):
    return re.sub(r'(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])', '_', s).lower()


def form(b):
    w, h = b['w'], b['h']
    if (w, h) == (390, 844):
        return 'ponsel'
    if b.get('expand') == 'fill':
        return 'laptop' if w == 1440 else 'tablet'
    return 'a4' if {w, h} == {794, 1123} else 'lembar'


def dq(s):
    return "'" + s.replace('\\', '\\\\').replace("'", "\\'").replace('$', '\\$').replace('\n', '\\n') + "'"


def nilai(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return str(v)
    return dq(str(v))


order = [stem(f) for f in CANVAS['order']]
boards = {stem(f): b for f, b in CANVAS['boards'].items()}
assert len(order) == 199 == len(boards) == len(MANIFEST)

out = {}
for s in order:
    m = MANIFEST[s + '.dc.html']
    links = {stem(x) for x in m['links']}
    js = set() if s == 'AIBulan' else {stem(x) if x.endswith('.dc.html') else x for x in m.get('jsLinks', [])}
    out[s] = sorted((links | js | set(COMPUTED.get(s, []))) - {s})
inbound = {s: [] for s in order}
for s in order:
    for t in out[s]:
        assert t in boards, (s, t)
        inbound[t].append(s)
total = sum(len(v) for v in out.values())
assert total == 1282, total

# ---------------------------------------------------------------- boards.dart
L = ["// GENERATED by tool/gen_boards.py. Do not edit by hand.",
     "// ignore_for_file: lines_longer_than_80_chars",
     "",
     "enum Bentuk { ponsel, laptop, tablet, a4, lembar }",
     "",
     "class Tweak {",
     "  const Tweak(this.nama, this.editor, this.pilihan, this.bawaan);",
     "  final String nama;",
     "  /// 'boolean' or 'enum'.",
     "  final String editor;",
     "  final List<String>? pilihan;",
     "  final Object bawaan;",
     "}",
     "",
     "class Papan {",
     "  const Papan({required this.stem, required this.judul, required this.halaman, required this.bentuk,",
     "      required this.lebar, required this.tinggi, required this.tweaks, required this.keluar, required this.masuk});",
     "  final String stem, judul, halaman;",
     "  final Bentuk bentuk;",
     "  final double lebar, tinggi;",
     "  final List<Tweak> tweaks;",
     "  /// Boards this board links to (navigation.md 3.1).",
     "  final List<String> keluar;",
     "  /// Boards that link here.",
     "  final List<String> masuk;",
     "}",
     "",
     "/// Canvas pages in canvas order: (id, name).",
     "const halamanKanvas = <(String, String)>["]
for p in CANVAS['pages']:
    L.append(f"  ({dq(p['id'])}, {dq(p['name'])}),")
L += ["];", "", "/// Every board in canvas order.", "const semuaPapan = <Papan>["]
for s in order:
    b = boards[s]
    m = MANIFEST[s + '.dc.html']
    tw = []
    for n, t in m['tweaks'].items():
        opts = 'null' if t['options'] is None else '[' + ', '.join(dq(str(o)) for o in t['options']) + ']'
        tw.append(f"Tweak({dq(n)}, {dq(t['editor'])}, {opts}, {nilai(t['default'])})")
    L.append(f"  Papan(stem: {dq(s)}, judul: {dq(b['title'])}, halaman: {dq(b['page'])}, bentuk: Bentuk.{form(b)},")
    L.append(f"      lebar: {b['w']}, tinggi: {b['h']},")
    L.append(f"      tweaks: [{', '.join(tw)}],")
    L.append(f"      keluar: [{', '.join(dq(x) for x in out[s])}],")
    L.append(f"      masuk: [{', '.join(dq(x) for x in sorted(inbound[s]))}]),")
L += ["];", "",
      "final Map<String, Papan> papanMenurutStem = {for (final p in semuaPapan) p.stem: p};",
      "",
      "/// Stems of the boards with child routes (navigation.md 2.2).",
      "const papanBerAnak = <String>{" + ', '.join(dq(s) for s in CHILD) + "};",
      ""]
(PROTO / 'lib/boards.dart').write_text('\n'.join(L))

# ---------------------------------------------------------------- router.dart
imp = []
R = []
for s in order:
    b = boards[s]
    path = f"screens/{b['page']}/{snake(s)}.dart"
    imp.append(f"import '{path}';")
    kerangka = ', kerangka: Kerangka.masuk' if form(b) == 'ponsel' else ''
    if s not in CHILD:
        R.append(f"      GoRoute(path: {dq(s)}, pageBuilder: (c, s) => halaman(c, s, const {s}Screen(){kerangka})),")
        continue
    k = CHILD[s]
    R.append(f"      ShellRoute(")
    R.append(f"        builder: (_, _, child) => {k['kendali']}(child: child),")
    R.append(f"        routes: [")
    R.append(f"          GoRoute(path: {dq(s)}, pageBuilder: (c, s) => halaman(c, s, const DenganGenerasi(child: {s}Screen()){kerangka}), routes: [")
    for a in k['anak']:
        scr = f"DenganGenerasi(child: {s}Screen(anak: {dq(a['jalur'])}, param: s.pathParameters))"
        if a['masuk'] is None:
            tr = ''
        else:
            kurva = 'PalakatMotion.keluar' if a['kurva'] == 'keluar' else 'Curves.ease'
            tr = f", kerangka: Kerangka.{a['masuk']}, lama: const Duration(milliseconds: {a['ms']}), kurva: {kurva}"
        R.append(f"            GoRoute(path: {dq(a['jalur'])}, pageBuilder: (c, s) => halaman(c, s, {scr}{tr})),")
    R.append(f"          ]),")
    R.append(f"        ],")
    R.append(f"      ),")

router = f"""// GENERATED by tool/gen_boards.py. Do not edit by hand.
// ignore_for_file: lines_longer_than_80_chars

import 'package:flutter/material.dart';
import 'package:go_router/go_router.dart';

import 'motion/halaman.dart';
import 'motion/kerangka.dart';
import 'shell/kendali.dart';
import 'shell/komponen_galeri.dart';
import 'shell/peluncur.dart';
import 'shell/tidak_ditemukan.dart';
import 'theme/palakat_tokens.dart';
{chr(10).join(imp)}

GoRouter buatRouter() => GoRouter(
  initialLocation: '/',
  errorBuilder: (context, state) => TidakDitemukanScreen(lokasi: state.uri.toString()),
  routes: [
    GoRoute(path: '/', builder: (_, _) => const Peluncur(), routes: [
      GoRoute(path: '_komponen', builder: (_, _) => const KomponenGaleri()),
{chr(10).join(R)}
    ]),
  ],
);
"""
(PROTO / 'lib/router.dart').write_text(router)

# ---------------------------------------------------------------- stubs
dibuat = 0
for s in order:
    b = boards[s]
    f = PROTO / 'lib/screens' / b['page'] / f'{snake(s)}.dart'
    if f.exists():
        continue
    f.parent.mkdir(parents=True, exist_ok=True)
    stub = ["import 'package:flutter/material.dart';", "",
            "import '../../shell/belum_dibangun.dart';"]
    if s in CHILD:
        stub += ["import '../../shell/kendali.dart';", "",
                 f"class {s}Kendali extends StatefulWidget {{",
                 f"  const {s}Kendali({{super.key, required this.child}});",
                 "  final Widget child;",
                 "  @override",
                 f"  State<{s}Kendali> createState() => _{s}KendaliState();",
                 "}", "",
                 f"class _{s}KendaliState extends State<{s}Kendali> {{",
                 "  @override",
                 "  Widget build(BuildContext context) => GenerasiPapan(generasi: 0, child: widget.child);",
                 "}", "",
                 f"class {s}Screen extends StatelessWidget {{",
                 f"  const {s}Screen({{super.key, this.anak, this.param = const {{}}}});",
                 "  final String? anak;",
                 "  final Map<String, String> param;",
                 "  @override",
                 f"  Widget build(BuildContext context) => BelumDibangun(stem: {dq(s)}, anak: anak);",
                 "}", ""]
    else:
        stub += ["",
                 f"class {s}Screen extends StatelessWidget {{",
                 f"  const {s}Screen({{super.key}});",
                 "  @override",
                 f"  Widget build(BuildContext context) => const BelumDibangun(stem: {dq(s)});",
                 "}", ""]
    f.write_text('\n'.join(stub))
    dibuat += 1

print(f'ok: {len(order)} boards, {total} links, {sum(len(k["anak"]) for k in CHILD.values())} child routes, {dibuat} stubs created')
